CREATE TABLE IF NOT EXISTS deployment_runs (
    run_id CHAR(32) PRIMARY KEY,
    started_at DATETIME(6) NOT NULL,
    completed_at DATETIME(6) NULL,
    environment VARCHAR(20) NOT NULL,
    action ENUM('deploy', 'rollback') NOT NULL,
    model_id VARCHAR(50) NULL,
    trained_at DATETIME(6) NULL,
    feature_set_version VARCHAR(30) NULL,
    observation_date DATE NULL,
    scoring_mode ENUM('production') NOT NULL,
    customer_count INT UNSIGNED NOT NULL DEFAULT 0,
    prediction_count INT UNSIGNED NOT NULL DEFAULT 0,
    status ENUM('running', 'succeeded', 'failed', 'rolled_back') NOT NULL,
    failure_stage VARCHAR(30) NULL,
    error_summary VARCHAR(500) NULL,
    report_sha256 CHAR(64) NULL,
    model_sha256 CHAR(64) NULL,
    preprocessing_sha256 CHAR(64) NULL,
    feature_snapshot_sha256 CHAR(64) NULL,
    batch_sha256 CHAR(64) NULL,
    scored_at DATETIME(6) NULL,
    previous_run_id CHAR(32) NULL,
    rollback_target_run_id CHAR(32) NULL,
    reused_batch TINYINT(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (previous_run_id) REFERENCES deployment_runs(run_id),
    FOREIGN KEY (rollback_target_run_id) REFERENCES deployment_runs(run_id),
    CHECK (reused_batch IN (0, 1)),
    CHECK (status NOT IN ('succeeded', 'rolled_back') OR
           (environment = 'production' AND model_id IS NOT NULL AND completed_at IS NOT NULL
            AND batch_sha256 IS NOT NULL AND customer_count > 0 AND customer_count = prediction_count)),
    INDEX idx_deployment_model (model_id, started_at)
) ENGINE=InnoDB;
