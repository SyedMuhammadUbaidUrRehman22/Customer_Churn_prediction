CREATE TABLE IF NOT EXISTS business_validation (
    validation_id CHAR(64) PRIMARY KEY,
    analysis_sha256 CHAR(64) NOT NULL,
    model_id VARCHAR(50) NOT NULL,
    feature_set_version VARCHAR(30) NOT NULL,
    label_version VARCHAR(30) NOT NULL,
    validation_date DATE NOT NULL,
    evaluation_scope ENUM('benchmark', 'production') NOT NULL,
    scored_at DATETIME(6) NOT NULL,
    feature_snapshot_sha256 CHAR(64) NOT NULL,
    outreach_capacity INT UNSIGNED NOT NULL,
    threshold_used DOUBLE NOT NULL,
    selected_count INT UNSIGNED NOT NULL,
    selected_churners INT UNSIGNED NOT NULL,
    precision_at_n DOUBLE NOT NULL,
    recall_at_n DOUBLE NULL,
    population_count INT UNSIGNED NOT NULL,
    population_churners INT UNSIGNED NOT NULL,
    high_count INT UNSIGNED NOT NULL,
    medium_count INT UNSIGNED NOT NULL,
    low_count INT UNSIGNED NOT NULL,
    high_threshold DOUBLE NOT NULL,
    medium_threshold DOUBLE NOT NULL,
    low_threshold DOUBLE NOT NULL,
    pr_auc_min DOUBLE NULL,
    precision_at_k_min DOUBLE NULL,
    stakeholder_outreach_capacity INT UNSIGNED NULL,
    refresh_cadence VARCHAR(100) NULL,
    feature_importance_max DOUBLE NOT NULL,
    business_status ENUM('pending', 'approved', 'rejected') NOT NULL DEFAULT 'pending',
    stakeholder_status ENUM('pending', 'approved', 'rejected') NOT NULL DEFAULT 'pending',
    notes TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (analysis_sha256, outreach_capacity),
    FOREIGN KEY (model_id) REFERENCES model_registry(model_id),
    CHECK (evaluation_scope <> 'benchmark' OR
           (business_status <> 'approved' AND stakeholder_status <> 'approved')),
    CHECK (outreach_capacity = selected_count AND selected_count > 0
           AND selected_count <= population_count AND selected_churners <= selected_count
           AND selected_churners <= population_churners AND population_churners <= population_count),
    CHECK (high_count + medium_count + low_count = population_count),
    CHECK (low_threshold = 0 AND medium_threshold > 0
           AND medium_threshold < high_threshold AND high_threshold <= 1),
    CHECK (threshold_used BETWEEN 0 AND 1 AND precision_at_n BETWEEN 0 AND 1
           AND recall_at_n BETWEEN 0 AND 1),
    CHECK (pr_auc_min BETWEEN 0 AND 1 AND precision_at_k_min BETWEEN 0 AND 1),
    CHECK (feature_importance_max > 0 AND feature_importance_max <= 1),
    CHECK (stakeholder_outreach_capacity IS NULL OR stakeholder_outreach_capacity > 0)
) ENGINE=InnoDB;
