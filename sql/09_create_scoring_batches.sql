CREATE TABLE IF NOT EXISTS scoring_batches (
    batch_sha256 CHAR(64) PRIMARY KEY,
    run_id CHAR(32) NOT NULL,
    model_id VARCHAR(50) NOT NULL,
    feature_set_version VARCHAR(30) NOT NULL,
    label_version VARCHAR(30) NOT NULL,
    observation_date DATE NOT NULL,
    scored_at DATETIME(6) NOT NULL,
    customer_count INT UNSIGNED NOT NULL,
    feature_snapshot_sha256 CHAR(64) NOT NULL,
    report_sha256 CHAR(64) NOT NULL,
    low_threshold DOUBLE NOT NULL,
    high_threshold DOUBLE NOT NULL,
    future_window_days INT UNSIGNED NOT NULL,
    evaluation_threshold DOUBLE NULL,
    baseline_pr_auc DOUBLE NOT NULL,
    baseline_precision DOUBLE NOT NULL,
    baseline_recall DOUBLE NOT NULL,
    trained_at DATETIME(6) NOT NULL,
    FOREIGN KEY (run_id) REFERENCES deployment_runs(run_id),
    FOREIGN KEY (model_id) REFERENCES model_registry(model_id),
    CHECK (customer_count > 0 AND future_window_days > 0),
    CHECK (feature_set_version <> 'telco_snapshot_v1' AND label_version <> 'telco_snapshot_v1'),
    CHECK (0 < low_threshold AND low_threshold < high_threshold AND high_threshold <= 1),
    CHECK (evaluation_threshold IS NULL OR (evaluation_threshold > 0 AND evaluation_threshold <= 1)),
    CHECK (baseline_pr_auc BETWEEN 0 AND 1 AND baseline_precision BETWEEN 0 AND 1
           AND baseline_recall BETWEEN 0 AND 1),
    INDEX idx_scoring_batch_date (feature_set_version, observation_date)
) ENGINE=InnoDB;
